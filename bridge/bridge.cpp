static void CollectField(value, int id, void *cookie)
{
    ((std::vector<int> *)cookie)->push_back(id);
}

static const char kUnit = 0x1f;   // separates items inside one reply
static const int kMaxDumpItems = 400;

static std::string Dump(value v)
{
    std::string out = Repr(v);
    if (IsNull(v)) return out;
    int t = val_type(v);
    if (t == valtArray)
    {
        int n = val_array_size(v);
        for (int i = 0; i < n && i < kMaxDumpItems; ++i)
        {
            out.push_back(kUnit);
            out += std::to_string(i) + "=" + Repr(val_array_i(v, i));
        }
    }
    else if (IsObject(v) && ClassObjectName(v).empty())
    {
        std::vector<int> ids;
        val_iter_fields(v, CollectField, &ids);
        for (size_t i = 0; i < ids.size() && i < (size_t)kMaxDumpItems; ++i)
        {
            std::string name = ToStd(val_field_name(ids[i]));
            out.push_back(kUnit);
            out += name + "=" + Repr(val_field(v, ids[i]));
        }
    }
    else if (IsObject(v))
    {
        value names = TypeCall1("getClassFields", v);
        int n = IsNull(names) ? 0 : val_array_size(names);
        for (int i = 0; i < n && i < kMaxDumpItems; ++i)
        {
            std::string name = ToStd(val_array_i(names, i));
            value f = val_field(v, val_id(name.c_str()));
            if (!IsNull(f) && val_type(f) == valtFunction) continue;   // statics only, not methods
            out.push_back(kUnit);
            out += name + "=" + Repr(f);
        }
    }
    return out;
}

static std::string NameList(value names)
{
    std::string out;
    int n = IsNull(names) ? 0 : val_array_size(names);
    for (int i = 0; i < n; ++i)
    {
        if (i) out.push_back(kUnit);
        out += ToStd(val_array_i(names, i));
    }
    return out;
}

// Drains a Haxe iterator (or an iterable, via iterator()) into reprs.
static std::string Iterate(value it)
{
    if (IsNull(it)) Fail("iterate null");
    value mk = val_field(it, val_id("iterator"));
    if (!IsNull(mk) && val_type(mk) == valtFunction) it = val_call0(mk);
    value hasNext = RawField(it, "hasNext"), next = RawField(it, "next");
    if (IsNull(hasNext) || IsNull(next)) Fail("not an iterator");
    std::string out; int n = 0;
    while (n < kMaxDumpItems && val_bool(val_call0(hasNext)))
    {
        if (n++) out.push_back(kUnit);
        out += Repr(val_call0(next));
    }
    return out;
}

static double Num(value v, double fallback)
{
    if (IsNull(v)) return fallback;
    int t = val_type(v);
    return (t == valtInt || t == valtFloat) ? val_number(v) : fallback;
}

// Every visible Starling text field under a display object, as "x,y,text" items in
// stage coordinates. Walking the tree here costs one request instead of hundreds.
// Rotation and skew are ignored: only used to put text in reading order.
static void WalkStage(value node, double ox, double oy, double sx, double sy,
                      std::string &out, int &budget, int depth)
{
    if (!IsObject(node) || depth > 40 || --budget < 0) return;
    value vis = val_field(node, val_id("__visible"));
    if (!IsNull(vis) && val_type(vis) == valtBool && !val_bool(vis)) return;
    if (Num(val_field(node, val_id("__alpha")), 1.0) <= 0.01) return;

    double x = ox + Num(val_field(node, val_id("__x")), 0) * sx;
    double y = oy + Num(val_field(node, val_id("__y")), 0) * sy;
    double nsx = sx * Num(val_field(node, val_id("__scaleX")), 1);
    double nsy = sy * Num(val_field(node, val_id("__scaleY")), 1);

    value text = val_field(node, val_id("_text"));
    if (!IsNull(text) && val_type(text) == valtString)
    {
        std::string s = ToStd(text);
        if (!s.empty())
        {
            // x,y,w,h: the text's own bounds let the client tell centred lines of one
            // paragraph from unrelated labels.
            value tb = val_field(node, val_id("_textBounds"));
            double bx = 0, by = 0, bw = 0, bh = 0;
            if (IsObject(tb))
            {
                bx = Num(val_field(tb, val_id("x")), 0); by = Num(val_field(tb, val_id("y")), 0);
                bw = Num(val_field(tb, val_id("width")), 0); bh = Num(val_field(tb, val_id("height")), 0);
            }
            char pos[128];
            snprintf(pos, sizeof pos, "%.0f,%.0f,%.0f,%.0f,", x + bx * nsx, y + by * nsy, bw * nsx, bh * nsy);
            if (!out.empty()) out.push_back(kUnit);
            out += pos + Escape(s);
        }
        return;   // a text field's children are its glyph meshes
    }

    value kids = val_field(node, val_id("__children"));
    if (IsNull(kids)) return;
    if (val_type(kids) != valtArray) kids = val_field(kids, val_id("__array"));   // openfl Vector
    if (IsNull(kids) || val_type(kids) != valtArray) return;
    int n = val_array_size(kids);
    for (int i = 0; i < n; ++i) WalkStage(val_array_i(kids, i), x, y, nsx, nsy, out, budget, depth + 1);
}

#ifndef _WIN32
// What /EHa does on Windows: a bad pointer met while serving a request becomes an error
// reply instead of a crash. Only faults on the main thread inside a Guard are caught;
// every other fault goes to whatever handler was installed before ours. Unwinding by
// longjmp skips destructors (a small leak), which beats taking the game down.
static sigjmp_buf *volatile g_faultJump = nullptr;
static pthread_t g_faultThread;
static struct sigaction g_prevSegv, g_prevBus;

static void FaultHandler(int sig, siginfo_t *info, void *ctx)
{
    if (g_faultJump && pthread_equal(pthread_self(), g_faultThread)) siglongjmp(*g_faultJump, sig);
    struct sigaction &prev = sig == SIGBUS ? g_prevBus : g_prevSegv;
    if ((prev.sa_flags & SA_SIGINFO) && prev.sa_sigaction) { prev.sa_sigaction(sig, info, ctx); return; }
    if (prev.sa_handler != SIG_DFL && prev.sa_handler != SIG_IGN && prev.sa_handler) { prev.sa_handler(sig); return; }
    // No one else wants it: restore the default and let the fault happen again, for real.
    signal(sig, SIG_DFL);
}

// Idempotent, and cheap enough to call before each batch of requests in case the game
// installed a handler of its own after us (ours then chains to it).
static void InstallFaultHandler()
{
    struct sigaction cur;
    if (sigaction(SIGSEGV, nullptr, &cur) == 0 && (cur.sa_flags & SA_SIGINFO) && cur.sa_sigaction == FaultHandler) return;
    struct sigaction sa = {};
    sa.sa_sigaction = FaultHandler;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigemptyset(&sa.sa_mask);
    sigaction(SIGSEGV, &sa, &g_prevSegv);
    sigaction(SIGBUS, &sa, &g_prevBus);
}
#endif

template <typename F> static std::string Guard(F f)
{
#ifdef _WIN32
    try { return f(); }
    catch (BridgeError &e) { return "!" + Escape(e.msg); }
    catch (...) { return "!exception in game code"; }
#else
    sigjmp_buf jump;
    sigjmp_buf *outer = g_faultJump;   // Guards nest (pluck)
    if (sigsetjmp(jump, 1)) { g_faultJump = outer; return std::string("!memory fault in game code"); }
    g_faultThread = pthread_self();
    g_faultJump = &jump;
    std::string r;
    try { r = f(); }
    catch (BridgeError &e) { r = "!" + Escape(e.msg); }
    catch (...) { r = "!exception in game code"; }
    g_faultJump = outer;
    return r;
#endif
}

static std::vector<std::string> Split(const std::string &s, char sep)
{
    std::vector<std::string> parts; size_t a = 0, b;
    while ((b = s.find(sep, a)) != std::string::npos) { parts.push_back(s.substr(a, b - a)); a = b + 1; }
    parts.push_back(s.substr(a));
    return parts;
}

// Request:  <id> TAB <command> TAB <argument>
// Reply:    <id> TAB <result>        a result starting with '!' is an error
static void Execute(int client, const std::string &line)
{
    std::vector<std::string> f = Split(line, '\t');
    if (f.size() < 2) return;
    const std::string &id = f[0], &cmd = f[1];
    std::string arg = f.size() > 2 ? f[2] : "";
    std::string result;

    if (cmd == "ping") result = "pong";
    else if (cmd == "eval") result = Guard([&] { return Repr(EvalString(arg)); });
    else if (cmd == "dump") result = Guard([&] { return Dump(EvalString(arg)); });
    else if (cmd == "iter") result = Guard([&] { return Iterate(EvalString(arg)); });
    else if (cmd == "batch")
    {
        // Several evals in one frame, so the client sees one consistent state.
        std::vector<std::string> exprs = Split(arg, kUnit);
        for (size_t i = 0; i < exprs.size(); ++i)
        {
            if (i) result.push_back(kUnit);
            result += Guard([&] { return Repr(EvalString(exprs[i])); });
        }
    }
    else if (cmd == "statics") result = Guard([&] { return NameList(TypeCall1("getClassFields", EvalString(arg))); });
    else if (cmd == "members") result = Guard([&] { return NameList(TypeCall1("getInstanceFields", EvalString(arg))); });
    else if (cmd == "set") result = Guard([&] {
        // set <object expr> US <field> US <value expr>
        std::vector<std::string> a = Split(arg, kUnit);
        if (a.size() != 3) Fail("usage: set obj US field US value");
        value o = EvalString(a[0]); if (IsNull(o)) Fail("set on null");
        alloc_field(o, val_id(a[1].c_str()), EvalString(a[2]));
        return std::string("ok"); });
    else if (cmd == "seti") result = Guard([&] {
        // seti <array expr> US <index> US <value expr>
        std::vector<std::string> a = Split(arg, kUnit);
        if (a.size() != 3) Fail("usage: seti array US index US value");
        value o = EvalString(a[0]); if (IsNull(o) || val_type(o) != valtArray) Fail("not an array");
        int i = atoi(a[1].c_str()); if (i < 0 || i >= val_array_size(o)) Fail("index out of range");
        val_array_set_i(o, i, EvalString(a[2]));
        return std::string("ok"); });
    else if (cmd == "pluck") result = Guard([&] {
        // pluck <array expr> US <path> US <path> ...   One record (RS separated) per element,
        // holding the repr of each path evaluated against that element. A path is what would
        // follow the element in an expression: "label", "enemytemplate.name", "connections.length".
        std::vector<std::string> a = Split(arg, kUnit);
        value arr = EvalString(a[0]);
        if (IsNull(arr) || val_type(arr) != valtArray) Fail("not an array");
        int n = val_array_size(arr);
        std::string out;
        for (int i = 0; i < n && i < kMaxDumpItems; ++i)
        {
            if (i) out.push_back(0x1e);
            long long h = NewHandle(val_array_i(arr, i));
            for (size_t k = 1; k < a.size(); ++k)
            {
                if (k > 1) out.push_back(kUnit);
                out += Guard([&] { return Repr(EvalString("#" + std::to_string(h) + "." + a[k])); });
            }
        }
        return out; });
    else if (cmd == "stagetext") result = Guard([&] {
        std::string out; int budget = 20000;
        WalkStage(EvalString(arg), 0, 0, 1.0, 1.0, out, budget, 0);
        return out; });
    else if (cmd == "probe") result = Guard([&] {
        // Developer aid. This build has Type.getClassFields stripped, so statics cannot be
        // listed; instead try every name in a word list (one per line) and report the ones
        // that read non-null. Functions are reported by name only.
        value v = EvalString(arg); if (IsNull(v)) Fail("null");
        FILE *wl = f.size() > 3 ? fopen(f[3].c_str(), "r") : nullptr;
        if (!wl) Fail("word list not readable");
        std::string out = Repr(v); char name[256];
        while (fgets(name, sizeof name, wl))
        {
            size_t n = strlen(name);
            while (n && (name[n - 1] == '\n' || name[n - 1] == '\r')) name[--n] = 0;
            if (!n) continue;
            value fv = val_field(v, val_id(name));
            if (IsNull(fv)) continue;
            out.push_back(kUnit);
            out += name;
            out += "=";
            out += val_type(fv) == valtFunction ? std::string("fn") : Repr(fv);
        }
        fclose(wl);
        return out; });
    else if (cmd == "peek") result = Guard([&] {
        // Raw qwords of an object, for working out hxcpp layouts. '*' marks a slot that
        // looks like a Haxe object and can be turned into a handle with "adopt".
        value v = EvalString(arg); if (IsNull(v)) Fail("null");
        std::string out; char tmp[64];
        for (int off = 0; off < 96; off += 8)
        {
            void *q = *(void **)((char *)v + off);
            snprintf(tmp, sizeof tmp, "+%d=%p%s", off, q, PlausibleObject(q) ? "*" : "");
            if (off) out.push_back(kUnit);
            out += tmp;
        }
        return out; });
    else if (cmd == "adopt") result = Guard([&] {
        size_t sp = arg.rfind(' '); if (sp == std::string::npos) Fail("usage: adopt <expr> <offset>");
        value v = EvalString(arg.substr(0, sp)); if (IsNull(v)) Fail("null");
        void *q = *(void **)((char *)v + atoi(arg.c_str() + sp + 1));
        if (!PlausibleObject(q)) Fail("slot does not hold a Haxe object");
        return Repr((value)q); });
    else if (cmd == "setapp") result = Guard([&] { SetPin(PinApp, EvalString(arg)); g_bootState = 1; g_bootAttempts = 0; return std::string("ok"); });
    else if (cmd == "pin") result = Guard([&] { return Repr(Pin(atoi(arg.c_str()))); });
    else if (cmd == "setresolver") result = Guard([&] { SetPin(PinResolver, EvalString(arg)); return std::string("ok"); });
    else result = "!unknown command";

    Send(client, id + "\t" + result);
}

