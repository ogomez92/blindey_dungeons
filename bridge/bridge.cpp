// ---------------------------------------------------------------- handles
//
// Objects handed to the client are kept alive in a Haxe array held by a GC root.
// It is a ring: old handles expire rather than leak.

struct BridgeError { std::string msg; };
static void Fail(const std::string &m) { throw BridgeError{m}; }

static const int kRing = 16384;
static value *g_ringRoot = nullptr;
static long long g_nextHandle = 1;   // 0 is reserved for the application object

static value *g_pinRoot = nullptr;   // array of long-lived values: [0]=app, [1]=resolver, [2]=Type, [3]=Std
enum { PinApp = 0, PinResolver = 1, PinType = 2, PinStd = 3, PinCallback = 4, PinCount = 8 };

static value Pin(int i) { return g_pinRoot && *g_pinRoot ? val_array_i(*g_pinRoot, i) : nullptr; }
static void SetPin(int i, value v) { if (g_pinRoot && *g_pinRoot) val_array_set_i(*g_pinRoot, i, v); }

static long long NewHandle(value v)
{
    long long h = g_nextHandle++;
    val_array_set_i(*g_ringRoot, (int)(h % kRing), v);
    return h;
}

static value FromHandle(long long h)
{
    if (h == 0) { value a = Pin(PinApp); if (!a) Fail("application object not captured"); return a; }
    if (h < 0 || h >= g_nextHandle || h <= g_nextHandle - kRing) Fail("stale handle");
    return val_array_i(*g_ringRoot, (int)(h % kRing));
}

// ---------------------------------------------------------------- reflection helpers

static bool IsNull(value v) { return v == nullptr || val_type(v) == valtNull; }

static value Str(const std::string &s) { return alloc_string_len(s.data(), (int)s.size()); }

static std::string ToStd(value v)
{
    if (IsNull(v)) return "";
    const char *s = val_string(v);
    return s ? std::string(s) : std::string();
}

static value RawField(value o, const char *name)
{
    if (IsNull(o)) Fail(std::string("field '") + name + "' of null");
    return val_field(o, val_id(name));
}

// Plain field first; hxcpp does not run property getters on a dynamic read, so fall
// back to get_<name>() when the field reads as null.
static value GetField(value o, const std::string &name)
{
    value v = RawField(o, name.c_str());
    if (!IsNull(v)) return v;
    value g = val_field(o, val_id(("get_" + name).c_str()));
    if (!IsNull(g) && val_type(g) == valtFunction) return val_call0(g);
    return v;
}

static value CallN(value fn, std::vector<value> &args)
{
    if (IsNull(fn) || val_type(fn) != valtFunction) Fail("not a function");
    switch (args.size())
    {
        case 0: return val_call0(fn);
        case 1: return val_call1(fn, args[0]);
        case 2: return val_call2(fn, args[0], args[1]);
        case 3: return val_call3(fn, args[0], args[1], args[2]);
        default: return val_callN(fn, args.data(), (int)args.size());
    }
}

static value ResolveClass(const std::string &name)
{
    value r = Pin(PinResolver);
    if (IsNull(r)) Fail("class resolver not available");
    value c = val_call1(r, Str(name));
    if (IsNull(c)) Fail("unknown class " + name);
    return c;
}

static value TypeCall1(const char *fn, value a)
{
    value t = Pin(PinType);
    if (IsNull(t)) return nullptr;
    value f = val_field(t, val_id(fn));
    if (IsNull(f)) return nullptr;
    return val_call1(f, a);
}

static std::string ClassNameOf(value o)
{
    value c = TypeCall1("getClass", o);
    if (IsNull(c)) return "";
    return ToStd(TypeCall1("getClassName", c));
}

// Non-empty only when v is a Class object.
static std::string ClassObjectName(value v)
{
    if (IsNull(v) || val_type(v) != valtObject) return "";
    return ToStd(TypeCall1("getClassName", v));
}

static bool IsObject(value v)
{
    if (IsNull(v)) return false;
    int t = val_type(v);
    return t == valtObject || t == valtInstance;
}

static std::string StdString(value v)
{
    value s = Pin(PinStd);
    if (IsNull(s)) return "?";
    value f = val_field(s, val_id("string"));
    if (IsNull(f)) return "?";
    return ToStd(val_call1(f, v));
}

static std::string Escape(const std::string &s)
{
    std::string o; o.reserve(s.size() + 8);
    for (unsigned char c : s)
    {
        switch (c)
        {
            case '\\': o += "\\\\"; break;
            case '\n': o += "\\n"; break;
            case '\r': o += "\\r"; break;
            case '\t': o += "\\t"; break;
            case 0x1e: o += "\\x1e"; break;
            case 0x1f: o += "\\x1f"; break;
            default: o.push_back((char)c);
        }
    }
    return o;
}

// One-line description of a value. Objects, arrays and functions get a handle.
static std::string Repr(value v)
{
    if (v == nullptr) return "n";
    char num[64];
    int t = val_type(v);
    switch (t)
    {
        case valtNull: return "n";
        case valtInt: snprintf(num, sizeof num, "i:%d", val_int(v)); return num;
        case valtFloat: snprintf(num, sizeof num, "f:%.10g", val_number(v)); return num;
        case valtBool: return val_bool(v) ? "b:1" : "b:0";
        case valtString: return "s:" + Escape(ToStd(v));
        case valtArray:
            snprintf(num, sizeof num, "a:#%lld:%d", NewHandle(v), val_array_size(v)); return num;
        case valtFunction:
            snprintf(num, sizeof num, "fn:#%lld:%d", NewHandle(v), val_fun_nargs(v)); return num;
        case valtEnum:
            snprintf(num, sizeof num, "e:#%lld:", NewHandle(v));
            return num + Escape(StdString(v));
        case valtObject:
        case valtInstance:
        {
            std::string cls = ClassObjectName(v);
            snprintf(num, sizeof num, "%s:#%lld:", cls.empty() ? "o" : "c", NewHandle(v));
            return num + Escape(cls.empty() ? ClassNameOf(v) : cls);
        }
        default:
            snprintf(num, sizeof num, "x:%d", t); return num;
    }
}

// ---------------------------------------------------------------- expressions
//
//   {states.Title}          class by name
//   #12                     handle from an earlier reply;  #0 is the lime application
//   .field                  field, or get_field() when the field reads null
//   [3]  ["key"]            array index / map get
//   (args)                  call the function value on the left
//   123  1.5  "text"  true  false  null

struct Parser
{
    const char *p;
    explicit Parser(const char *s) : p(s) {}
    void Ws() { while (*p == ' ') ++p; }
    bool Eat(char c) { Ws(); if (*p == c) { ++p; return true; } return false; }
};

static value Eval(Parser &ps);

static std::string ParseIdent(Parser &ps)
{
    const char *s = ps.p;
    while (isalnum((unsigned char)*ps.p) || *ps.p == '_') ++ps.p;
    if (s == ps.p) Fail("identifier expected");
    return std::string(s, ps.p);
}

static value ParseRoot(Parser &ps)
{
    ps.Ws();
    char c = *ps.p;
    if (c == '{')
    {
        const char *s = ++ps.p;
        while (*ps.p && *ps.p != '}') ++ps.p;
        if (*ps.p != '}') Fail("} expected");
        std::string name(s, ps.p); ++ps.p;
        return ResolveClass(name);
    }
    if (c == '[')
    {
        // Array literal, for calls that take one (Type.createInstance(cls, [args])).
        ++ps.p;
        value arr = alloc_array(0);
        if (!ps.Eat(']'))
        {
            do { val_array_push(arr, Eval(ps)); } while (ps.Eat(','));
            if (!ps.Eat(']')) Fail("] expected");
        }
        return arr;
    }
    if (c == '#')
    {
        ++ps.p;
        char *end; long long h = strtoll(ps.p, &end, 10);
        if (end == ps.p) Fail("handle number expected");
        ps.p = end;
        return FromHandle(h);
    }
    if (c == '"')
    {
        std::string s; ++ps.p;
        while (*ps.p && *ps.p != '"')
        {
            if (*ps.p == '\\' && ps.p[1])
            {
                ++ps.p;
                s.push_back(*ps.p == 'n' ? '\n' : *ps.p == 't' ? '\t' : *ps.p);
                ++ps.p;
            }
            else s.push_back(*ps.p++);
        }
        if (*ps.p != '"') Fail("unterminated string");
        ++ps.p;
        return Str(s);
    }
    if (c == '-' || isdigit((unsigned char)c))
    {
        char *end; double d = strtod(ps.p, &end);
        bool isFloat = false;
        for (const char *q = ps.p; q < end; ++q) if (*q == '.' || *q == 'e' || *q == 'E') isFloat = true;
        ps.p = end;
        return isFloat ? alloc_float(d) : alloc_int((int)d);
    }
    if (!strncmp(ps.p, "true", 4)) { ps.p += 4; return alloc_bool(true); }
    if (!strncmp(ps.p, "false", 5)) { ps.p += 5; return alloc_bool(false); }
    if (!strncmp(ps.p, "null", 4)) { ps.p += 4; return alloc_null(); }
    Fail(std::string("unexpected '") + c + "'");
    return nullptr;
}

static value Eval(Parser &ps)
{
    value cur = ParseRoot(ps);
    for (;;)
    {
        ps.Ws();
        if (*ps.p == '.')
        {
            ++ps.p;
            cur = GetField(cur, ParseIdent(ps));
        }
        else if (*ps.p == '[')
        {
            ++ps.p;
            value idx = Eval(ps);
            if (!ps.Eat(']')) Fail("] expected");
            if (IsNull(cur)) Fail("index of null");
            if (val_type(cur) == valtArray)
            {
                int i = val_int(idx);
                if (i < 0 || i >= val_array_size(cur)) Fail("index out of range");
                cur = val_array_i(cur, i);
            }
            else
            {
                value get = RawField(cur, "get");
                if (IsNull(get)) Fail("not indexable");
                cur = val_call1(get, idx);
            }
        }
        else if (*ps.p == '(')
        {
            ++ps.p;
            std::vector<value> args;
            if (!ps.Eat(')'))
            {
                do { args.push_back(Eval(ps)); } while (ps.Eat(','));
                if (!ps.Eat(')')) Fail(") expected");
            }
            cur = CallN(cur, args);
        }
        else return cur;
    }
}

static value EvalString(const std::string &s)
{
    Parser ps(s.c_str());
    value v = Eval(ps);
    ps.Ws();
    if (*ps.p) Fail(std::string("trailing input at '") + ps.p + "'");
    return v;
}

