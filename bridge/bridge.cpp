// DiceyA11y bridge - a proxy for the game's lime.ndll.
//
// Dicey Dungeons is a native hxcpp build, so there is no managed runtime to patch.
// It does however load lime.ndll dynamically through hxcpp's CFFI loader, and hands
// every ndll the full CFFI reflection API through hx_set_loader. This DLL takes
// lime.ndll's place, forwards every export to the original (lime_orig.dll, see
// exports.def) and intercepts three of them:
//
//   hx_set_loader                                  -> gives us the CFFI API
//   lime_application_event_manager_register__prime -> gives us a live Haxe object
//   lime_window_context_flip__prime                -> gives us a per-frame tick on
//                                                     the game's main thread
//
// On that tick it serves a small reflection protocol over a named pipe. All game
// knowledge lives in the companion; this file knows nothing about Dicey Dungeons
// beyond how to find a class resolver.
//
// Build: bridge\build.ps1 (MSVC, /EHa so catch(...) also stops access violations).

