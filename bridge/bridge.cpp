typedef void (*RegisterFn)(value callback, value eventObject);
typedef void (*FlipFn)(value window);
typedef void *(*PrimeGetter)(const char *sig);

static RegisterFn g_realRegister = nullptr;
static FlipFn g_realFlip = nullptr;

static void HookedRegister(value callback, value eventObject)
{
    try { if (g_pinRoot && IsNull(Pin(PinCallback))) SetPin(PinCallback, callback); } catch (...) {}
    g_realRegister(callback, eventObject);
}

static void HookedFlip(value window)
{
    g_realFlip(window);
    Tick();
}

// A __prime getter returns an abstract (kind 0x102) wrapping the raw function pointer.
// The pointer sits in the abstract's payload; read it back with val_data's layout-free
// cousin: ask the original for the abstract, then build our own around the hook.
typedef void *(*val_data_t)(value);
static val_data_t val_data = nullptr;

static void *WrapPrime(const char *name, const char *sig, const char *expectSig, void **realOut, void *hook)
{
    PrimeGetter getter = Orig() ? (PrimeGetter)GetProcAddress(Orig(), name) : nullptr;
    if (!getter) { Log("%s missing in lime_orig", name); return nullptr; }
    void *abstractValue = getter(sig);
    if (!abstractValue) return nullptr;
    if (!sig || strcmp(sig, expectSig) != 0 || !val_data || !alloc_abstract)
    {
        Log("%s: signature '%s' not the expected '%s', passing through", name, sig ? sig : "(null)", expectSig);
        return abstractValue;
    }
    void *real = val_data((value)abstractValue);
    if (!real) { Log("%s: could not read function pointer, passing through", name); return abstractValue; }
    *realOut = real;
    Log("%s hooked", name);
    return alloc_abstract((void *)(uintptr_t)(valtAbstractBase + 2), hook);
}

