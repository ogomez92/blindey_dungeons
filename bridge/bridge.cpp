// A lock that is a critical section on Windows and a mutex elsewhere.
struct Lock
{
#ifdef _WIN32
    CRITICAL_SECTION cs;
    void Init() { InitializeCriticalSection(&cs); }
    void Enter() { EnterCriticalSection(&cs); }
    void Leave() { LeaveCriticalSection(&cs); }
#else
    std::mutex m;
    void Init() {}
    void Enter() { m.lock(); }
    void Leave() { m.unlock(); }
#endif
};

